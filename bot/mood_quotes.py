def clean_song_title(title: str) -> str:
    """提取纯净基础歌名（兼容现场版本、日文译名与数字序号）"""
    t = title.strip()
    t = re.sub(r"^\d+[\.\s_、-]+", "", t)
    t_no_paren = re.sub(r"[\(（\[【].*?[\)）\]】]", "", t).strip()
    t_no_paren = re.sub(r"(Live|live|现场版|不插电|伴奏|Remix).*$", "", t_no_paren, flags=re.I).strip()
    t_no_paren = t_no_paren.replace("の", "之")
    if any("\u4e00" <= c <= "\u9fa5" for c in t_no_paren):
        return t_no_paren
    inners = re.findall(r"[\(（\[【]([^\)）\]】]+)[\)）\]】]", t)
    for inn in inners:
        cn_part = re.sub(r"[^\u4e00-\u9fa5]", "", inn)
        if cn_part:
            return cn_part
    return t_no_paren

def get_song_exact_quote(title: str, lyrics: Optional[str] = None) -> str:
    """
    严密获取指定曲目的真实歌词金句，绝不张冠李戴！
    优先查精选金句表，未命中则从该歌曲的真实歌词中切取，无词则展示纯器乐提示。
    """
    base_title = clean_song_title(title)
    
    # 1. 优先精准匹配经典金句字典
    for k, q in SONG_EXACT_QUOTES.items():
        if k == base_title or k in base_title or base_title in k:
            return q

    # 2. 从歌曲真实歌词中按行动态提取连续代表歌词
    if lyrics:
        lines = [
            l.strip() for l in lyrics.splitlines() 
            if l.strip() and not l.strip().startswith("[") and not any(kw in l for kw in ["作词", "作曲", "编曲", "吉他", "贝斯", "鼓手", "录音", "混音"])
        ]
        if lines:
            mid = len(lines) // 2
            cand = "，".join(lines[mid:mid+2])
            if cand:
                if not cand.endswith(("。", "！", "？")):
                    cand += "。"
                return cand

    # 3. 兜底器乐提示
    return "纯器乐演奏曲目 · 闭上双眼感受现场空气的震颤。"

